func TestBootstrapUsesTheWorkspaceContext(t *testing.T) {
	ws, _ := workspace(t, "contextName: lab\n")
	for _, tc := range []struct{ env, flag, want string }{{"", "", "lab"}, {"env", "", "env"}, {"env", "cli", "cli"}} {
		t.Setenv("KUBE_CONTEXT_NAME", tc.env)
		var out bytes.Buffer
		c := empty()
		o := options{dryRun: true}
		o.workspace.ContextName = tc.flag
		if err := run(context.Background(), helm4(), c.connect, term(&out, "", false), ws, os.Getenv, strings.NewReader(""), o); err != nil {
			t.Fatal(err)
		}
		if !slices.Equal(c.asked, []string{tc.want}) {
			t.Errorf("env %q, flag %q: connected to %v, want %s", tc.env, tc.flag, c.asked, tc.want)
		}
	}
}

