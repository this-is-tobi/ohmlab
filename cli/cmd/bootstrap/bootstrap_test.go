const versionCheck = "helm version --template '{{.Version}}'"

func write(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

// workspace makes an instance repository holding one instance, lab, whose
// ohmlab.yaml points at a product checkout beside it and ends with extra.
func workspace(t *testing.T, extra string) (ws, product string) {
	t.Helper()
	dir := t.TempDir()
	product = filepath.Join(dir, "ohmlab")
	write(t, filepath.Join(product, "charts", "ohmlab", "Chart.yaml"), "apiVersion: v2\nname: ohmlab\nversion: 0.0.0\n")
	ws = filepath.Join(dir, "lab-repo")
	write(t, filepath.Join(ws, "ohmlab.yaml"), "product: ../ohmlab\n"+extra)
	inst := filepath.Join(ws, "argo-cd", "instances", "lab")
	write(t, filepath.Join(inst, "instance.yaml"), "instance:\n  name: lab\n")
	write(t, filepath.Join(inst, "core.yaml"), "apps:\n- app: ohmlab\n  namespace: argocd-system\n  chartPath: charts/ohmlab\n")
	write(t, filepath.Join(inst, "values", "core", "ohmlab.yaml"), "argo-cd:\n  enabled: true\n")
	t.Setenv("KUBE_CONTEXT_NAME", "")
	t.Setenv("ARGOCD_ADMIN_PASSWORD", "")
	return ws, product
}

// connector hands out one fake cluster and records the contexts asked for.
type connector struct {
	cluster *bootstraptest.Cluster
	asked   []string
}

func (c *connector) connect(_, context string) (bs.Cluster, string, error) {
	c.asked = append(c.asked, context)
	return c.cluster, "https://kind:6443", nil
}

func empty() *connector { return &connector{cluster: &bootstraptest.Cluster{}} }

// installed is a cluster bootstrapped before, whose Argo CD generated pw-123.
func installed() *connector {
	return &connector{cluster: &bootstraptest.Cluster{CRDs: map[string]bool{bs.GatewayAPIMarker: true, bs.ArgoCDMarker: true}, Password: "pw-123"}}
}

// helm4 is a helm that says it is Helm 4 and does everything else.
func helm4() *runnertest.Fake {
	return &runnertest.Fake{Handle: func(c runner.Cmd) error {
		if c.Args[0] == "version" {
			_, err := io.WriteString(c.Stdout, "v4.3.1")
			return err
		}
		return nil
	}}
}

func term(out *bytes.Buffer, in string, yes bool) *ui.UI {
	return ui.New(ui.Options{Out: out, Err: out, In: strings.NewReader(in), Mode: ui.Human, Yes: yes})
}

func machine(out *bytes.Buffer, yes bool) *ui.UI {
	return ui.New(ui.Options{Out: out, Err: out, In: strings.NewReader(""), Mode: ui.JSON, Yes: yes})
}

func lines(calls []runner.Cmd) []string {
	var out []string
	for _, c := range calls {
		out = append(out, c.String())
	}
	return out
}

func TestDryRunChangesNothing(t *testing.T) {
	ws, product := workspace(t, "")
	var out bytes.Buffer
	r, c := helm4(), empty()
	if err := run(context.Background(), r, c.connect, term(&out, "", false), ws, os.Getenv, strings.NewReader(""), options{dryRun: true}); err != nil {
		t.Fatalf("%v\n%s", err, out.String())
	}
	for _, want := range []string{
		"Instance lab (" + filepath.Join(ws, "argo-cd", "instances", "lab") + ")",
		"Context ohmlab, server https://kind:6443",
		"Chart " + filepath.Join(product, "charts", "ohmlab") + " (a directory)",
		"Release ohmlab in argocd-system",
		"Gateway API CRDs: missing, installs " + bs.GatewayAPIVersion + " (experimental channel)",
		"Argo CD: missing, phase 1 installs it alone first",
		"Admin password: generated by Argo CD",
		"Would fetch and apply " + bs.GatewayAPIURL(bs.GatewayAPIVersion),
	} {
		if !strings.Contains(out.String(), want) {
			t.Errorf("output lacks %q:\n%s", want, out.String())
		}
	}
	if n := strings.Count(out.String(), "Would run: helm"); n != 3 {
		t.Errorf("%d helm commands planned, want 3 (dependencies, phase 1, phase 2):\n%s", n, out.String())
	}
	if got := lines(r.Calls); !slices.Equal(got, []string{versionCheck}) {
		t.Errorf("ran %q, want the version check alone", got)
	}
	if len(c.cluster.Applied) != 0 || strings.Contains(out.String(), "[y/N]") {
		t.Errorf("a dry run applied %d objects or asked:\n%s", len(c.cluster.Applied), out.String())
	}
}

func TestBootstrapAsksFirstAndDefaultsToNo(t *testing.T) {
	ws, _ := workspace(t, "")
	var out bytes.Buffer
	r := helm4()
	err := run(context.Background(), r, installed().connect, term(&out, "\n", false), ws, os.Getenv, strings.NewReader(""), options{})
	if err == nil || !strings.Contains(err.Error(), "not confirmed") {
		t.Errorf("got %v, want not confirmed", err)
	}
	if !strings.Contains(out.String(), "Bootstrap lab on context ohmlab (https://kind:6443)? [y/N]") {
		t.Errorf("the question is missing:\n%s", out.String())
	}
	if got := lines(r.Calls); !slices.Equal(got, []string{versionCheck}) {
		t.Errorf("ran %q, want the version check alone", got)
	}
}

