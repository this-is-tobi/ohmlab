func TestBootstrapRefusesAnExample(t *testing.T) {
	ws, _ := workspace(t, "")
	var out bytes.Buffer
	r := helm4()
	o := options{yes: true}
	o.workspace.Instance = "_example"
	err := run(context.Background(), r, installed().connect, term(&out, "", true), ws, os.Getenv, strings.NewReader(""), o)
	if err == nil || !strings.Contains(err.Error(), "is an example") {
		t.Errorf("got %v, want instance.Pick's refusal", err)
	}
	if len(r.Calls) != 0 {
		t.Errorf("ran %q", lines(r.Calls))
	}
}

func TestBootstrapNeedsTheValuesFile(t *testing.T) {
	ws, _ := workspace(t, "")
	values := filepath.Join(ws, "argo-cd", "instances", "lab", "values", "core", "ohmlab.yaml")
	if err := os.Remove(values); err != nil {
		t.Fatal(err)
	}
	var out bytes.Buffer
	err := run(context.Background(), helm4(), installed().connect, term(&out, "", true), ws, os.Getenv, strings.NewReader(""), options{yes: true})
	if err == nil || !strings.Contains(err.Error(), values) {
		t.Errorf("got %v, want an error naming %s", err, values)
	}
}

func TestBootstrapWarnsWithoutAnOhmlabEntry(t *testing.T) {
	ws, _ := workspace(t, "")
	write(t, filepath.Join(ws, "argo-cd", "instances", "lab", "core.yaml"), "apps:\n- app: other\n")
	var out bytes.Buffer
	if err := run(context.Background(), helm4(), empty().connect, term(&out, "", false), ws, os.Getenv, strings.NewReader(""), options{dryRun: true}); err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out.String(), "lab has no ohmlab app in core.yaml") {
		t.Errorf("no warning about the missing ohmlab app:\n%s", out.String())
	}
}
